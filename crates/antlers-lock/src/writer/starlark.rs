/// Options for customizing Starlark macro output.
///
/// This generates legacy WORKSPACE-compatible `.bzl` files with helper macros
/// for loading Maven dependencies, similar to `rules_jvm_external`'s pattern.
#[derive(Debug, Clone)]
pub struct StarlarkMacroOptions {
    /// Name of the main function that loads all dependencies (default: `"maven_dependencies"`).
    pub function_name: String,
    /// Repository URL (default: Maven Central).
    pub repository_url: String,
    /// Group artifacts by their group prefix in comments (default: true).
    pub group_by_prefix: bool,
    /// Include docstrings in the output (default: true).
    pub include_docstring: bool,
}

impl Default for StarlarkMacroOptions {
    fn default() -> Self {
        Self {
            function_name: "maven_dependencies".to_string(),
            repository_url: MAVEN_CENTRAL_URL.to_string(),
            group_by_prefix: true,
            include_docstring: true,
        }
    }
}

impl StarlarkMacroOptions {
    /// Creates new options with default settings.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the main function name.
    #[must_use]
    pub fn with_function_name(mut self, name: impl Into<String>) -> Self {
        self.function_name = name.into();
        self
    }

    /// Sets the repository URL.
    #[must_use]
    pub fn with_repository_url(mut self, url: impl Into<String>) -> Self {
        self.repository_url = url.into();
        self
    }

    /// Sets whether to group artifacts by prefix in comments.
    #[must_use]
    pub const fn with_group_by_prefix(mut self, group: bool) -> Self {
        self.group_by_prefix = group;
        self
    }

    /// Sets whether to include docstrings.
    #[must_use]
    pub const fn with_include_docstring(mut self, include: bool) -> Self {
        self.include_docstring = include;
        self
    }
}

/// Writes a lockfile to legacy WORKSPACE-compatible Starlark macro format.
///
/// Generates a `.bzl` file with:
/// - `http_jar` load statement
/// - `maybe` helper function for idempotent loading
/// - `_download` helper function for artifact downloads
/// - Main function (default: `maven_dependencies`) that loads all artifacts
///
/// # Example
///
/// ```ignore
/// use antlers_lock::{Lockfile, writer};
///
/// let lockfile = Lockfile::read_file("deps.lock.json")?;
/// let bzl = writer::write_starlark_macro(&lockfile)?;
/// std::fs::write("repositories.bzl", bzl)?;
/// ```
///
/// Usage in WORKSPACE:
///
/// ```starlark
/// load("//:repositories.bzl", "maven_dependencies")
/// maven_dependencies()
/// ```
///
/// # Errors
///
/// This function is infallible in practice as writing to a String never fails.
pub fn write_starlark_macro(lockfile: &Lockfile) -> Result<String> {
    write_starlark_macro_with_options(lockfile, &StarlarkMacroOptions::default())
}

/// Writes a lockfile to legacy WORKSPACE-compatible Starlark macro format with custom options.
///
/// # Example
///
/// ```ignore
/// use antlers_lock::{Lockfile, writer::{self, StarlarkMacroOptions}};
///
/// let lockfile = Lockfile::read_file("deps.lock.json")?;
/// let options = StarlarkMacroOptions::default()
///     .with_function_name("load_maven_jars")
///     .with_repository_url("https://maven.example.com/repo");
/// let bzl = writer::write_starlark_macro_with_options(&lockfile, &options)?;
/// ```
///
/// # Errors
///
/// This function is infallible in practice as writing to a String never fails.
#[allow(clippy::unnecessary_wraps)]
pub fn write_starlark_macro_with_options(
    lockfile: &Lockfile,
    options: &StarlarkMacroOptions,
) -> Result<String> {
    let mut output = String::new();

    // Write file header/docstring
    if options.include_docstring {
        output.push_str("\"\"\"Maven dependencies for WORKSPACE.\n\n");
        output.push_str("This file is generated by antlers. Do not edit manually.\n\n");
        output.push_str("Usage:\n");
        let _ = writeln!(
            output,
            "    load(\"//:repositories.bzl\", \"{}\")",
            options.function_name
        );
        let _ = writeln!(output, "    {}()", options.function_name);
        output.push_str("\"\"\"\n\n");
    } else {
        output.push_str("# Generated by antlers\n\n");
    }

    // Write load statement
    output.push_str("load(\"@bazel_tools//tools/build_defs/repo:http.bzl\", \"http_jar\")\n\n");

    // Write maybe helper
    write_maybe_helper(&mut output, options);
    output.push('\n');

    // Write _download helper
    write_download_helper(&mut output, options);
    output.push('\n');

    // Write main function
    write_main_function(&mut output, lockfile, options);

    Ok(output)
}

/// Writes the `maybe` helper function for idempotent rule loading.
fn write_maybe_helper(output: &mut String, options: &StarlarkMacroOptions) {
    output.push_str("def maybe(repo_rule, name, **kwargs):\n");
    if options.include_docstring {
        output
            .push_str("    \"\"\"Execute a repository rule if it hasn't been defined yet.\"\"\"\n");
    }
    output.push_str("    if name not in native.existing_rules():\n");
    output.push_str("        repo_rule(name = name, **kwargs)\n");
}

/// Writes the `_download` helper function for downloading artifacts.
fn write_download_helper(output: &mut String, options: &StarlarkMacroOptions) {
    output.push_str("def _download(name, path, sha256):\n");
    if options.include_docstring {
        output.push_str("    \"\"\"Download a Maven artifact.\"\"\"\n");
    }
    output.push_str("    maybe(\n");
    output.push_str("        http_jar,\n");
    output.push_str("        name = name,\n");
    let _ = writeln!(
        output,
        "        url = \"{}/\" + path,",
        escape_starlark(&options.repository_url)
    );
    output.push_str("        sha256 = sha256,\n");
    output.push_str("    )\n");
}

/// Writes the main function that loads all dependencies.
fn write_main_function(output: &mut String, lockfile: &Lockfile, options: &StarlarkMacroOptions) {
    let _ = writeln!(output, "def {}():", options.function_name);

    if options.include_docstring {
        let _ = writeln!(output, "    \"\"\"Load all Maven dependencies.\n");
        let _ = writeln!(output, "    This function should be called from WORKSPACE.");
        output.push_str("    \"\"\"\n");
    }

    if lockfile.artifacts.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    // Sort artifacts for deterministic output
    let mut sorted_artifacts: Vec<_> = lockfile.artifacts.iter().collect();
    sorted_artifacts.sort_by(|(k1, _), (k2, _)| k1.cmp(k2));

    // Group by prefix if enabled
    let mut current_prefix = String::new();

    for (coord, artifact) in sorted_artifacts {
        // Add group comment if grouping is enabled
        if options.group_by_prefix {
            let prefix = coord
                .split(':')
                .next()
                .unwrap_or("")
                .split('.')
                .take(2)
                .collect::<Vec<_>>()
                .join(".");

            if prefix != current_prefix {
                if !current_prefix.is_empty() {
                    output.push('\n');
                }
                let _ = writeln!(output, "    # {prefix}");
                current_prefix = prefix;
            }
        }

        let target_name = coordinate_to_target_name(coord);
        let path = coordinate_to_path(coord, &artifact.version, &artifact.packaging);

        // Use serde_starlark to serialize the _download() function call
        let download_call = DownloadCall {
            name: target_name,
            path,
            sha256: artifact.sha256.clone(),
        };

        // Serialize and indent each line for proper function body formatting
        if let Ok(call_str) = serde_starlark::to_string(&download_call) {
            for line in call_str.lines() {
                let _ = writeln!(output, "    {line}");
            }
        }
    }
}

/// Converts a Maven coordinate to a Bazel target name.
///
/// This is the public version of the coordinate conversion function,
/// exposed for use by consumers who need to generate compatible target names.
///
/// # Example
///
/// ```
/// use antlers_lock::writer::starlark::coordinate_to_target_name;
///
/// assert_eq!(
///     coordinate_to_target_name("com.google.guava:guava"),
///     "com_google_guava_guava"
/// );
/// assert_eq!(
///     coordinate_to_target_name("org.jetbrains.kotlin:kotlin-stdlib"),
///     "org_jetbrains_kotlin_kotlin_stdlib"
/// );
/// ```
#[must_use]
pub fn coordinate_to_target_name(coord: &str) -> String {
    coord
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

