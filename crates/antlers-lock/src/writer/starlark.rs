//! Starlark writers for Bazel compatibility.
//!
//! This module provides writers for generating Starlark files from lockfiles:
//!
//! - [`write_starlark_dict`] - PACKAGES-style data structure for simple data access
//! - [`write_module_extension`] - bzlmod MODULE.bazel compatible extension
//! - [`write_starlark_macro`] - Legacy WORKSPACE-compatible repositories.bzl
//!
//! # Dict Format Example
//!
//! ```ignore
//! use antlers_lock::{Lockfile, writer::starlark};
//!
//! let lockfile = Lockfile::read_file("deps.lock.json")?;
//! let bzl = starlark::write_starlark_dict(&lockfile)?;
//! std::fs::write("maven_artifacts.bzl", bzl)?;
//! ```
//!
//! The dict format generates PACKAGES-style data structures:
//!
//! ```starlark
//! """Maven artifact definitions generated by antlers."""
//!
//! MAVEN_CENTRAL = "https://repo1.maven.org/maven2"
//!
//! ARTIFACTS = {
//!     "com.google.guava:guava": {
//!         "33.0.0-jre": {
//!             "path": "com/google/guava/guava/33.0.0-jre/guava-33.0.0-jre.jar",
//!             "sha256": "abc123...",
//!         },
//!     },
//! }
//!
//! MAVEN_ARTIFACTS = [
//!     {"coord": "com.google.guava:guava:33.0.0-jre", "sha256": "abc123...", "deps": []},
//! ]
//! ```
//!
//! # Module Extension Example
//!
//! ```ignore
//! use antlers_lock::{Lockfile, writer::starlark};
//!
//! let lockfile = Lockfile::read_file("deps.lock.json")?;
//! let bzl = starlark::write_module_extension(&lockfile)?;
//! std::fs::write("maven.bzl", bzl)?;
//! ```
//!
//! Usage in MODULE.bazel:
//!
//! ```starlark
//! maven = use_extension("//:maven.bzl", "maven")
//! maven.install()
//! use_repo(maven, "com_google_guava_guava", "org_jetbrains_kotlin_kotlin_stdlib")
//! ```
//!
//! # Macro Format Example (Legacy WORKSPACE)
//!
//! ```ignore
//! use antlers_lock::{Lockfile, writer::starlark};
//!
//! let lockfile = Lockfile::read_file("deps.lock.json")?;
//! let bzl = starlark::write_starlark_macro(&lockfile)?;
//! std::fs::write("repositories.bzl", bzl)?;
//! ```
//!
//! Usage in WORKSPACE:
//!
//! ```starlark
//! load("//:repositories.bzl", "maven_dependencies")
//! maven_dependencies()
//! ```
//!
//! The macro format generates:
//!
//! ```starlark
//! """Maven dependencies for WORKSPACE."""
//!
//! load("@bazel_tools//tools/build_defs/repo:http.bzl", "http_jar")
//!
//! def maybe(repo_rule, name, **kwargs):
//!     if name not in native.existing_rules():
//!         repo_rule(name = name, **kwargs)
//!
//! def _download(name, path, sha256):
//!     maybe(http_jar, name = name, url = "https://repo1.maven.org/maven2/" + path, sha256 = sha256)
//!
//! def maven_dependencies():
//!     _download(name = "com_google_guava_guava", path = "...", sha256 = "...")
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde::Serialize;
// serde_starlark is used for proper Starlark AST serialization

use crate::Lockfile;
use crate::error::Result;

// =============================================================================
// Starlark AST Types (serde-serializable)
// =============================================================================

// For dict output, we use BTreeMap directly since serde_starlark serializes
// maps as Starlark dicts. Named structs would serialize as function calls.

/// Represents a value that can be serialized to Starlark.
/// This enum allows mixing strings and arrays in dict values.
#[derive(Debug, Clone, Serialize)]
#[serde(untagged)]
enum StarlarkValue {
    String(String),
    Array(Vec<String>),
}

/// A `_download()` function call for the macro format.
/// Serializes to: `_download(name = "...", path = "...", sha256 = "...")`
#[derive(Debug, Clone, Serialize)]
#[serde(rename = "_download")]
struct DownloadCall {
    name: String,
    path: String,
    sha256: String,
}

/// Default Maven Central repository URL.
pub const MAVEN_CENTRAL_URL: &str = "https://repo1.maven.org/maven2";

// =============================================================================
// Dict Format (PACKAGES-style data structures)
// =============================================================================

/// Options for customizing Starlark dict output.
#[derive(Debug, Clone)]
pub struct StarlarkDictOptions {
    /// Repository URL (default: Maven Central).
    pub repository_url: String,
    /// Include dependencies in output (default: true).
    pub include_deps: bool,
    /// Variable name for the nested dict (default: "ARTIFACTS").
    pub dict_name: String,
    /// Variable name for the flat list (default: `MAVEN_ARTIFACTS`).
    pub list_name: String,
    /// Include the flat list format (default: true).
    pub include_flat_list: bool,
    /// Include repository URL constant (default: true).
    pub include_repo_constant: bool,
}

impl Default for StarlarkDictOptions {
    fn default() -> Self {
        Self {
            repository_url: MAVEN_CENTRAL_URL.to_string(),
            include_deps: true,
            dict_name: "ARTIFACTS".to_string(),
            list_name: "MAVEN_ARTIFACTS".to_string(),
            include_flat_list: true,
            include_repo_constant: true,
        }
    }
}

impl StarlarkDictOptions {
    /// Creates options with a custom repository URL.
    #[must_use]
    pub fn with_repository_url(mut self, url: impl Into<String>) -> Self {
        self.repository_url = url.into();
        self
    }

    /// Sets whether to include dependencies.
    #[must_use]
    pub const fn with_include_deps(mut self, include: bool) -> Self {
        self.include_deps = include;
        self
    }

    /// Sets the variable name for the nested dict.
    #[must_use]
    pub fn with_dict_name(mut self, name: impl Into<String>) -> Self {
        self.dict_name = name.into();
        self
    }

    /// Sets the variable name for the flat list.
    #[must_use]
    pub fn with_list_name(mut self, name: impl Into<String>) -> Self {
        self.list_name = name.into();
        self
    }

    /// Sets whether to include the flat list format.
    #[must_use]
    pub const fn with_include_flat_list(mut self, include: bool) -> Self {
        self.include_flat_list = include;
        self
    }

    /// Sets whether to include the repository URL constant.
    #[must_use]
    pub const fn with_include_repo_constant(mut self, include: bool) -> Self {
        self.include_repo_constant = include;
        self
    }
}

/// Writes a lockfile to Starlark dict format with default options.
///
/// Generates a PACKAGES-style data structure with:
/// - A nested dict indexed by `group:artifact`, then version
/// - A flat list for simpler iteration
///
/// # Example
///
/// ```ignore
/// use antlers_lock::{Lockfile, writer};
///
/// let lockfile = Lockfile::read_file("deps.lock.json")?;
/// let starlark = writer::write_starlark_dict(&lockfile)?;
/// std::fs::write("maven_deps.bzl", starlark)?;
/// ```
///
/// # Errors
///
/// This function is infallible in practice as writing to a String never fails.
pub fn write_starlark_dict(lockfile: &Lockfile) -> Result<String> {
    write_starlark_dict_with_options(lockfile, &StarlarkDictOptions::default())
}

/// Writes a lockfile to Starlark dict format with custom options.
///
/// # Example
///
/// ```ignore
/// use antlers_lock::{Lockfile, writer::{self, StarlarkDictOptions}};
///
/// let lockfile = Lockfile::read_file("deps.lock.json")?;
/// let options = StarlarkDictOptions::default()
///     .with_dict_name("PACKAGES")
///     .with_include_deps(false);
/// let starlark = writer::write_starlark_dict_with_options(&lockfile, &options)?;
/// ```
///
/// # Errors
///
/// This function is infallible in practice as writing to a String never fails.
#[allow(clippy::unnecessary_wraps)]
pub fn write_starlark_dict_with_options(
    lockfile: &Lockfile,
    options: &StarlarkDictOptions,
) -> Result<String> {
    let mut output = String::new();

    // Write docstring
    output.push_str("\"\"\"Maven artifact definitions generated by antlers.\"\"\"\n\n");

    // Write repository URL constant using serde_starlark
    if options.include_repo_constant {
        let assignment =
            serde_starlark::Assignment::new("MAVEN_CENTRAL", options.repository_url.as_str());
        output.push_str(&serde_starlark::to_string(&assignment).unwrap_or_else(|_| String::new()));
        output.push('\n');
    }

    // Write nested dict (ARTIFACTS)
    write_nested_dict(&mut output, lockfile, options);

    // Write flat list (MAVEN_ARTIFACTS)
    if options.include_flat_list {
        output.push('\n');
        write_flat_list(&mut output, lockfile, options);
    }

    Ok(output)
}

/// Builds the nested dict structure for artifacts.
/// Returns a nested `BTreeMap` that serializes to Starlark dict syntax.
fn build_nested_dict(
    lockfile: &Lockfile,
    options: &StarlarkDictOptions,
) -> BTreeMap<String, BTreeMap<String, BTreeMap<String, StarlarkValue>>> {
    let mut result: BTreeMap<String, BTreeMap<String, BTreeMap<String, StarlarkValue>>> =
        BTreeMap::new();

    for (key, artifact) in &lockfile.artifacts {
        let path = build_maven_path_with_classifier(
            key,
            &artifact.version,
            &artifact.packaging,
            artifact.classifier.as_deref(),
        );

        // Build version info as a BTreeMap for proper dict serialization
        let mut version_info: BTreeMap<String, StarlarkValue> = BTreeMap::new();
        version_info.insert("path".to_string(), StarlarkValue::String(path));
        version_info.insert(
            "sha256".to_string(),
            StarlarkValue::String(artifact.sha256.clone()),
        );

        // Only include deps if enabled and non-empty
        if options.include_deps && !artifact.dependencies.is_empty() {
            let deps_with_versions: Vec<String> = artifact
                .dependencies
                .iter()
                .filter_map(|dep_key| {
                    lockfile
                        .artifacts
                        .get(dep_key)
                        .map(|dep_artifact| format!("{}:{}", dep_key, dep_artifact.version))
                })
                .collect();
            version_info.insert("deps".to_string(), StarlarkValue::Array(deps_with_versions));
        }

        let version_map = result.entry(key.clone()).or_default();
        version_map.insert(artifact.version.clone(), version_info);
    }

    result
}

/// Writes the nested dict format indexed by group:artifact, then version.
fn write_nested_dict(output: &mut String, lockfile: &Lockfile, options: &StarlarkDictOptions) {
    output.push_str("# Artifact metadata indexed by group:artifact, then version\n");

    let nested_dict = build_nested_dict(lockfile, options);
    let assignment = serde_starlark::Assignment::new(options.dict_name.as_str(), &nested_dict);

    output.push_str(&serde_starlark::to_string(&assignment).unwrap_or_else(|_| {
        // Fallback to empty dict on serialization error
        format!("{} = {{}}\n", options.dict_name)
    }));
}

/// Builds the flat list of artifacts.
/// Returns a `Vec` of `BTreeMap`s that serialize to Starlark dict entries.
fn build_flat_list(
    lockfile: &Lockfile,
    options: &StarlarkDictOptions,
) -> Vec<BTreeMap<String, StarlarkValue>> {
    lockfile
        .artifacts
        .iter()
        .map(|(key, artifact)| {
            let coord = format!("{}:{}", key, artifact.version);

            let mut entry: BTreeMap<String, StarlarkValue> = BTreeMap::new();
            entry.insert("coord".to_string(), StarlarkValue::String(coord));
            entry.insert(
                "sha256".to_string(),
                StarlarkValue::String(artifact.sha256.clone()),
            );

            if options.include_deps {
                let deps_with_versions: Vec<String> = artifact
                    .dependencies
                    .iter()
                    .filter_map(|dep_key| {
                        lockfile
                            .artifacts
                            .get(dep_key)
                            .map(|dep_artifact| format!("{}:{}", dep_key, dep_artifact.version))
                    })
                    .collect();
                entry.insert("deps".to_string(), StarlarkValue::Array(deps_with_versions));
            }

            entry
        })
        .collect()
}

/// Writes the flat list format for simpler iteration.
fn write_flat_list(output: &mut String, lockfile: &Lockfile, options: &StarlarkDictOptions) {
    output.push_str("# Flat list for simpler iteration\n");

    let flat_list = build_flat_list(lockfile, options);
    let assignment = serde_starlark::Assignment::new(options.list_name.as_str(), &flat_list);

    output.push_str(&serde_starlark::to_string(&assignment).unwrap_or_else(|_| {
        // Fallback to empty list on serialization error
        format!("{} = []\n", options.list_name)
    }));
}

/// Builds a Maven-style path for an artifact with classifier support.
///
/// Format: `group/as/path/artifact/version/artifact-version[-classifier].extension`
fn build_maven_path_with_classifier(
    key: &str,
    version: &str,
    packaging: &str,
    classifier: Option<&str>,
) -> String {
    let parts: Vec<&str> = key.split(':').collect();
    if parts.len() != 2 {
        return String::new();
    }

    let group = parts[0];
    let artifact_id = parts[1];

    // Convert group to path (e.g., "org.example" -> "org/example")
    let group_path = group.replace('.', "/");

    // Build filename
    let filename = classifier.map_or_else(
        || format!("{artifact_id}-{version}.{packaging}"),
        |c| format!("{artifact_id}-{version}-{c}.{packaging}"),
    );

    format!("{group_path}/{artifact_id}/{version}/{filename}")
}

