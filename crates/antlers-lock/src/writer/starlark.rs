/// Options for module extension generation.
#[derive(Debug, Clone)]
pub struct ModuleExtensionOptions {
    /// Extension name (default: "maven").
    pub extension_name: String,
    /// Repository URL (default: Maven Central).
    pub repository_url: String,
    /// Whether to include detailed doc comments.
    pub include_docs: bool,
}

impl Default for ModuleExtensionOptions {
    fn default() -> Self {
        Self {
            extension_name: "maven".to_string(),
            repository_url: MAVEN_CENTRAL_URL.to_string(),
            include_docs: true,
        }
    }
}

impl ModuleExtensionOptions {
    /// Creates new options with default settings.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the extension name.
    #[must_use]
    pub fn with_extension_name(mut self, name: impl Into<String>) -> Self {
        self.extension_name = name.into();
        self
    }

    /// Sets the repository URL.
    #[must_use]
    pub fn with_repository_url(mut self, url: impl Into<String>) -> Self {
        self.repository_url = url.into();
        self
    }

    /// Disables doc comments in the output.
    #[must_use]
    pub const fn without_docs(mut self) -> Self {
        self.include_docs = false;
        self
    }
}

/// Writes a lockfile to a bzlmod module extension format.
///
/// Uses default options (extension name "maven", Maven Central repository).
///
/// # Errors
///
/// Returns an error if the lockfile contains invalid data.
pub fn write_module_extension(lockfile: &Lockfile) -> Result<String> {
    write_module_extension_with_options(lockfile, &ModuleExtensionOptions::default())
}

/// Writes a lockfile to a bzlmod module extension format with custom options.
///
/// # Errors
///
/// Returns an error if the lockfile contains invalid data.
#[allow(clippy::unnecessary_wraps)]
pub fn write_module_extension_with_options(
    lockfile: &Lockfile,
    options: &ModuleExtensionOptions,
) -> Result<String> {
    let mut output = String::new();

    // Header with module docstring
    if options.include_docs {
        output.push_str("\"\"\"Maven module extension for bzlmod.\n\n");
        output.push_str("This file is generated by antlers. Do not edit manually.\n");
        output.push_str("\"\"\"\n\n");
    } else {
        output.push_str("# Generated by antlers\n\n");
    }

    // Load statement for http_jar
    output.push_str("load(\"@bazel_tools//tools/build_defs/repo:http.bzl\", \"http_jar\")\n\n");

    // Repository constant
    let _ = writeln!(
        output,
        "_MAVEN_REPOSITORY = \"{}\"",
        escape_starlark(&options.repository_url)
    );
    output.push('\n');

    // Write the pinned artifacts dictionary
    write_pinned_artifacts(&mut output, lockfile, options);
    output.push('\n');

    // Write the tag_class for install
    write_install_tag_class(&mut output, options);
    output.push('\n');

    // Write the implementation function
    write_impl_function(&mut output, options);
    output.push('\n');

    // Write the module_extension declaration
    write_extension_declaration(&mut output, options);
    output.push('\n');

    // Write usage comment showing use_repo
    write_usage_comment(&mut output, lockfile, options);

    Ok(output)
}

/// Builds a pinned artifact entry as a `BTreeMap` for proper dict serialization.
fn build_pinned_artifact_entry(
    lockfile: &Lockfile,
    coord: &str,
    artifact: &crate::LockedArtifact,
    options: &ModuleExtensionOptions,
) -> BTreeMap<String, StarlarkValue> {
    let repo_name = coordinate_to_repo_name(coord);
    let path = coordinate_to_path(coord, &artifact.version, &artifact.packaging);

    let mut entry: BTreeMap<String, StarlarkValue> = BTreeMap::new();

    // Add required fields in alphabetical order (BTreeMap will sort them)
    let deps: Vec<String> = artifact
        .dependencies
        .iter()
        .map(|dep| {
            let dep_version = lockfile
                .artifacts
                .get(dep)
                .map_or("*", |a| a.version.as_str());
            format!("{dep}:{dep_version}")
        })
        .collect();

    entry.insert("deps".to_string(), StarlarkValue::Array(deps));
    entry.insert("name".to_string(), StarlarkValue::String(repo_name));
    entry.insert("path".to_string(), StarlarkValue::String(path));
    entry.insert(
        "sha256".to_string(),
        StarlarkValue::String(artifact.sha256.clone()),
    );

    // Add repository URL if different from default
    if let Some(ref repo) = artifact.repository {
        let repo_url = repo.trim_end_matches('/');
        let default_url = options.repository_url.trim_end_matches('/');
        if repo_url != default_url {
            entry.insert(
                "repository".to_string(),
                StarlarkValue::String(repo.clone()),
            );
        }
    }

    entry
}

/// Writes the `_PINNED_ARTIFACTS` dictionary using `serde_starlark`.
fn write_pinned_artifacts(
    output: &mut String,
    lockfile: &Lockfile,
    options: &ModuleExtensionOptions,
) {
    // Build the pinned artifacts dict
    let mut pinned: BTreeMap<String, BTreeMap<String, StarlarkValue>> = BTreeMap::new();

    for (coord, artifact) in &lockfile.artifacts {
        let key = format!("{}:{}", coord, artifact.version);
        let entry = build_pinned_artifact_entry(lockfile, coord, artifact, options);
        pinned.insert(key, entry);
    }

    // Serialize using serde_starlark for proper formatting
    let assignment = serde_starlark::Assignment::new("_PINNED_ARTIFACTS", &pinned);
    output.push_str(
        &serde_starlark::to_string(&assignment)
            .unwrap_or_else(|_| "_PINNED_ARTIFACTS = {}\n".to_string()),
    );
}

/// Writes the `_install` `tag_class`.
fn write_install_tag_class(output: &mut String, options: &ModuleExtensionOptions) {
    output.push_str("_install = tag_class(\n");

    if options.include_docs {
        output.push_str("    doc = \"Install pinned Maven dependencies.\",\n");
    }

    output.push_str("    attrs = {\n");
    output.push_str("        \"artifacts\": attr.string_list(\n");

    if options.include_docs {
        output.push_str(
            "            doc = \"Artifact coordinates to install (group:artifact:version). Empty means all.\",\n",
        );
    }

    output.push_str("            default = [],\n");
    output.push_str("        ),\n");
    output.push_str("        \"repository\": attr.string(\n");

    if options.include_docs {
        output.push_str("            doc = \"Maven repository URL.\",\n");
    }

    output.push_str("            default = _MAVEN_REPOSITORY,\n");
    output.push_str("        ),\n");
    output.push_str("    },\n");
    output.push_str(")\n");
}

/// Writes the implementation function.
fn write_impl_function(output: &mut String, options: &ModuleExtensionOptions) {
    let _ = writeln!(output, "def _{}_impl(module_ctx):", options.extension_name);

    if options.include_docs {
        let _ = writeln!(
            output,
            "    \"\"\"Implementation of the {} module extension.\"\"\"",
            options.extension_name
        );
    }

    output.push_str("    artifacts_to_install = {}\n\n");

    // Module iteration
    output.push_str("    for mod in module_ctx.modules:\n");
    output.push_str("        for install in mod.tags.install:\n");
    output.push_str(
        "            coords = install.artifacts if install.artifacts else _PINNED_ARTIFACTS.keys()\n",
    );
    output.push_str("            for coord in coords:\n");
    output.push_str("                if coord in _PINNED_ARTIFACTS:\n");
    output.push_str("                    artifacts_to_install[coord] = _PINNED_ARTIFACTS[coord]\n");
    output.push('\n');

    // Create http_jar rules
    output.push_str("    for coord, info in artifacts_to_install.items():\n");
    output.push_str("        repo_url = info.get(\"repository\", _MAVEN_REPOSITORY)\n");
    output.push_str("        http_jar(\n");
    output.push_str("            name = info[\"name\"],\n");
    output.push_str("            url = repo_url.rstrip(\"/\") + \"/\" + info[\"path\"],\n");
    output.push_str("            sha256 = info[\"sha256\"],\n");
    output.push_str("        )\n");
}

/// Writes the `module_extension` declaration.
fn write_extension_declaration(output: &mut String, options: &ModuleExtensionOptions) {
    let _ = writeln!(output, "{} = module_extension(", options.extension_name);

    if options.include_docs {
        output.push_str("    doc = \"Maven dependency management from pinned lockfile.\",\n");
    }

    let _ = writeln!(
        output,
        "    implementation = _{}_impl,",
        options.extension_name
    );
    output.push_str("    tag_classes = {\n");
    output.push_str("        \"install\": _install,\n");
    output.push_str("    },\n");
    output.push_str(")\n");
}

/// Writes a comment showing how to use the extension in MODULE.bazel.
fn write_usage_comment(output: &mut String, lockfile: &Lockfile, options: &ModuleExtensionOptions) {
    output.push_str("# Usage in MODULE.bazel:\n");
    output.push_str("# \n");
    let _ = writeln!(
        output,
        "# {} = use_extension(\"//:maven.bzl\", \"{}\")",
        options.extension_name, options.extension_name
    );
    let _ = writeln!(output, "# {}.install()", options.extension_name);

    // Build the use_repo line with all artifact names
    let mut repo_names: Vec<String> = lockfile
        .artifacts
        .keys()
        .map(|coord| coordinate_to_repo_name(coord))
        .collect();
    repo_names.sort();

    if repo_names.is_empty() {
        let _ = writeln!(output, "# use_repo({}, ...)", options.extension_name);
    } else if repo_names.len() <= 3 {
        let names = repo_names
            .iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(output, "# use_repo({}, {})", options.extension_name, names);
    } else {
        let _ = writeln!(output, "# use_repo(");
        let _ = writeln!(output, "#     {},", options.extension_name);
        for name in &repo_names {
            let _ = writeln!(output, "#     \"{name}\",");
        }
        output.push_str("# )\n");
    }
}

/// Converts a Maven coordinate to a Bazel repository name.
///
/// Example: `com.google.guava:guava` -> `com_google_guava_guava`
fn coordinate_to_repo_name(coord: &str) -> String {
    coord
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// Converts a Maven coordinate to a repository path.
///
/// Example: "com.google.guava:guava", "33.0.0-jre", "jar"
///       -> "com/google/guava/guava/33.0.0-jre/guava-33.0.0-jre.jar"
fn coordinate_to_path(coord: &str, version: &str, packaging: &str) -> String {
    let parts: Vec<&str> = coord.split(':').collect();
    if parts.len() < 2 {
        return String::new();
    }

    let group = parts[0];
    let artifact = parts[1];
    let extension = if packaging.is_empty() {
        "jar"
    } else {
        packaging
    };

    let group_path = group.replace('.', "/");
    format!("{group_path}/{artifact}/{version}/{artifact}-{version}.{extension}")
}

/// Escapes a string for Starlark context.
fn escape_starlark(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

